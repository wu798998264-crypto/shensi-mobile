import assert from 'node:assert/strict';
import {mkdtemp,readFile,realpath} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
const packageRoot=resolve(process.env.SHENSI_TEST_PACKAGE_ROOT||'.');
const {startServer}=await import(pathToFileURL(join(packageRoot,'apps/desktop/server.mjs')));
let clipboard;
const dataRoot=await mkdtemp(join(await realpath(tmpdir()),'shensi-transfer-'));
const host=await startServer({dataRoot,desktop:{copyCardFiles:async payload=>{clipboard=payload;return {copied:true};}}});
const svc=host.service;
try{
 const [source]=await svc.list();const dest=await svc.create('目标笔记本');
 const id=source.id,targetId=dest.id||dest.library?.id;assert(targetId);
 const board=async id=>svc.createDocument(id,{kind:'whiteboard',expectedStateStamp:(await svc.load(id)).stateStamp});
 const a=await board(id),b=await board(targetId);
 const png=await readFile(join(packageRoot,'packages/ui/logo.png'));
 const attachment=await svc.asset(id,{name:'参考.png',mimeType:'image/png',base64:png.toString('base64'),whiteboardDocumentId:a.documentId,whiteboardMediaKind:'image'});
 const live=await svc.load(id),canvas=live.state.documents[a.documentId].canvas;
 const base={x:0,y:0,width:200,height:100};canvas.nodes.push({...base,id:'aa',type:'text',text:'A'}, {...base,id:'bb',type:'file',kind:'image',file:attachment.relativePath});
 canvas.edges.push({id:'ab',fromNode:'aa',toNode:'bb',fromSide:'right',toSide:'left'});
 await svc.save(id,{state:live.state,expectedStateStamp:live.stateStamp});
 const api=async(path,body)=>{const resp=await fetch(host.origin+'/api/'+path,{method:'POST',headers:{'x-shensi-token':host.token,'content-type':'application/json'},body:JSON.stringify(body)});const data=await resp.json();if(!resp.ok)throw Error(data.message||data.error);return data;};
 const nodeIds=['aa','bb'],expectedStateStamp=(await svc.load(id)).stateStamp;
 const {sourceHash}=await api('board/copy',{id,documentId:a.documentId,nodeIds,expectedStateStamp,token:crypto.randomUUID()});
 const req={id:targetId,documentId:b.documentId,sourceId:id,sourceDocumentId:a.documentId,nodeIds,sourceHash,expectedStateStamp:(await svc.load(targetId)).stateStamp,operationId:'cards-'+crypto.randomUUID(),cut:true};
 await assert.rejects(api('board/transfer',{...req,sourceHash:'changed'}));assert.equal((await svc.load(id)).state.documents[a.documentId].canvas.nodes.length,2);
 const result=await api('board/transfer',req);assert.deepEqual(result.nodeIds,nodeIds);
 assert.deepEqual(await api('board/transfer',req),result);
 assert.equal((await svc.load(id)).state.documents[a.documentId].canvas.nodes.length,0);
 const target=(await svc.load(targetId)).state.documents[b.documentId].canvas;
 assert.equal(target.nodes.length,2);assert.equal(target.edges.length,1);
 assert.deepEqual(await readFile((await svc.assetInfo(targetId,target.nodes[1].file,b.documentId)).absolutePath),png);
 console.log('PASS 跨笔记本移动文字、图片、连线，校验原图，冲突保留原卡，重复回执不重复创建');
 const assetResponse=await fetch(host.origin+'/api/board/assets',{headers:{'x-shensi-token':host.token}});
 const assets=(await assetResponse.json()).assets.filter(v=>v.current&&v.sourceDocumentId===b.documentId);
 const photo=assets.find(v=>v.coreNodeSnapshot.file);assert(photo);
 await api('board/assets/copy',{sourceIds:assets.map(a=>a.id)});assert.equal(clipboard.entries.length,2);
 assert.deepEqual(await readFile(clipboard.entries.find(e=>e.path).path),png);assert(clipboard.entries.some(v=>v.text==='A'));
 const link=await api('board/assets/file-link',{sourceId:photo.id});assert.equal(new URL(link.url).protocol,'file:');assert(!link.url.includes('token='));
 console.log('PASS 资产库批量复制交付文件、原文字及独立本机链接');
 const models=await api('official/models',{});const profile={id:'test-shared-channel',name:'双用途',provider:'自定义兼容接口',adapter:'api',model:'synthetic',baseUrl:'https://example.invalid',channel:'multimodal',channels:['text','image'],agentEngine:'codex_api',enabled:true};
 const saved=await api('official/models/save',{profile,expectedRevision:models.revision});
 const impact=await api('official/models/remove-impact',{profileId:profile.id});assert.deepEqual(impact.tasks,[]);
 let defaults=await api('official/models',{});
 for(const channel of ['text','image'])defaults=await api('official/models/default',{channel,profileId:profile.id,expectedRevision:defaults.defaultsRevision});
 assert.equal(defaults.defaultProfiles.image,profile.id);
 const changed=await api('official/models/detach-channel',{profileId:profile.id,channel:'image',expectedRevision:saved.revision});
 assert.deepEqual(changed.profiles.find(p=>p.id===profile.id).channels,['text']);await assert.rejects(api('official/models/detach-channel',{profileId:profile.id,channel:'text',expectedRevision:changed.revision}));
 const after=await api('official/models',{});
 assert.equal(after.defaultProfiles.image,'');assert.equal(after.defaultProfiles.text,profile.id);assert.deepEqual(after.legacyDefaultProfiles,defaults.legacyDefaultProfiles);
 console.log('PASS 移除图片用途后新卡图片默认清空，文字默认和旧卡快照保留，最后一个用途受保护，删除影响检查可用');
}finally{await host.close();}
